import { test, expect } from "@playwright/test";
import path from "node:path";
test("desktop catalogue, filtering, verified checkout and editing", async ({ page }) => {
  const errors: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  await page.setViewportSize({ width: 1440, height: 1100 });
  await page.goto("/");
  await expect(page.getByRole("heading", { name: "This cycle’s good things." })).toBeVisible();
  await expect(page.locator(".product-card")).toHaveCount(6);
  for (const img of await page.locator(".product-photo img").all()) await expect.poll(() => img.evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0);
  await page.screenshot({ path: "docs/screenshots/catalogue-desktop.png", fullPage: true });
  await page.getByRole("button", { name: "Drinks", exact: true }).click();
  await expect(page.locator(".product-card")).toHaveCount(1);
  await page.getByRole("button", { name: "All", exact: true }).click();
  const milk = page.locator(".product-card").filter({ has: page.getByRole("heading", { name: "Fresh full-cream milk" }) });
  await milk.getByRole("button", { name: "Add to basket" }).click();
  await page.getByRole("button", { name: "Sign in to place order" }).click();
  await page.getByRole("button", { name: "Fill demo details" }).click();
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.locator(".verified-account")).toContainText("Ava Thompson");
  await page.getByRole("button", { name: "Place my order", exact: true }).click();
  await expect(page.getByRole("heading", { name: "A little goodness, reserved." })).toBeVisible();
  await expect(page.locator(".confirmation-details")).toContainText("$3.20");
  await page.getByRole("link", { name: "View my order" }).click();
  await expect(page.getByRole("heading", { name: "Edit your favourites." })).toBeVisible();
  await page.getByRole("button", { name: "Increase Fresh full-cream milk" }).click();
  await page.getByRole("button", { name: "Save my changes" }).click();
  await expect(page.locator(".confirmation-details")).toContainText("$6.40");
  expect(errors).toEqual([]);
});
