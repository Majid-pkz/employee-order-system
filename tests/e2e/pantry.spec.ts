test("admin dashboard, product-photo editor, cycle control and PDF exports", async ({ page }) => {
  await page.goto("/admin");
  await expect(page.getByRole("heading", { name: "Welcome back." })).toBeVisible();
  await page.getByLabel("Username", { exact: true }).fill("demo-admin");
  await page.getByLabel("Password", { exact: true }).fill("AdminPantry2026!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Hello, Demo Administrator." })).toBeVisible();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "docs/screenshots/admin-desktop.png", fullPage: true });
  await page.getByRole("link", { name: "Catalogue", exact: true }).click();
  await page.getByRole("link", { name: "Add product" }).click();
  await expect(page.locator(".photo-option")).toHaveCount(6);
  await expect(page.locator('input[type="file"]')).toHaveCount(0);
  await page.getByRole("link", { name: "Orders & exports" }).click();
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Export Summary PDF" }).click();
  const file = await download;
  expect(file.suggestedFilename()).toMatch(/\.pdf$/);
  await file.saveAs(path.join("test-results", "summary.pdf"));
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: "docs/screenshots/admin-orders-mobile.png", fullPage: true });
  await page.getByRole("link", { name: "Sales cycles", exact: true }).click();
  await page.getByRole("link", { name: "Manage", exact: true }).first().click();
  page.once("dialog", dialog => dialog.accept());
  await page.getByRole("button", { name: "Close cycle" }).click();
  await expect(page.getByText("Status: closed", { exact: true })).toBeVisible();
  await page.goto("/");
  await expect(page.getByText("Orders are currently closed", { exact: true })).toBeVisible();
  await expect(page.locator(".product-card")).toHaveCount(0);
});
